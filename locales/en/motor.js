      H5: /\b(?:glass|glazing|shower screen|ceramic hob|power surge)\b/i,
      H9: /€\s?(?:\d{1,3}(?:,\d{3})+|\d+(?:\.\d+)?)/i,
      S2: /\b(?:operat\w+|surgery|hospital stay|admitted)\b/i,
      S3: /\b(?:dragging the injury along|already had|for a couple of years)\b/i,
      S4: /\b(?:I had an? \w+ operation|I've already had|I attach the invoice|\d+\s+(?:physiotherapy\s+)?sessions)\b/i,
      S5: /\b(?:outside the network|isn't in your network|not in your network|private clinic|don't think is in your network|provider network)\b/i,
      S7: /\breimburs\w+/i,
      S8: /\b(?:at work|workplace|mutual insurer|road accident)\b/i,
